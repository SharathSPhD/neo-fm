// Regenerates lib/agent/skill-pce-poem.ts from managed-agents (SKILL.md + the vendored pce-engine, tests excluded).
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative, resolve } from "node:path";

const root = resolve(import.meta.dirname, "../../..");
const skillMd = join(root, "managed-agents/skills/pce-poem/SKILL.md");
const engine = join(root, "managed-agents/pce-engine");
const files = { "pce-poem/SKILL.md": readFileSync(skillMd, "utf8") };
const walk = (dir) => {
  for (const name of readdirSync(dir).sort()) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) { if (name !== "tests" && name !== "__pycache__") walk(p); continue; }
    if (/\.(py|md|txt)$/.test(name) && name !== "PCE-LICENSE") files[`pce-poem/${relative(engine, p)}`] = readFileSync(p, "utf8");
  }
};
walk(engine);
const out = `// Generated by scripts/gen-skill.mjs from managed-agents/skills/pce-poem/SKILL.md + managed-agents/pce-engine (drift-checked by tests/agent-definitions.test.ts).
export const SKILL_FILES: Record<string, string> = ${JSON.stringify(files, null, 1)};
export const SKILL_PCE_POEM_MD = SKILL_FILES["pce-poem/SKILL.md"]!;
`;
writeFileSync(join(root, "apps/web/lib/agent/skill-pce-poem.ts"), out);
console.log(Object.keys(files).length, "files,", out.length, "bytes");
